function fold(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .toLowerCase();
}

/** Accent-insensitive search over titles, descriptions and file names. */
export function searchCodeSnippets(
  query: string,
  language: CodeFileLanguage | "all",
): CodeSnippet[] {
  const needle = fold(query.trim());
  return CODE_SNIPPETS.filter((snippet) => {
    if (language !== "all" && snippet.language !== language) {
      // HTML family includes stylesheets.
      if (!(language === "html" && snippet.language === "css")) return false;
    }
    if (!needle) return true;
    const haystack = fold(
      [
        snippet.title.vi,
        snippet.title.en,
        snippet.description.vi,
        snippet.description.en,
        snippet.fileName,
        snippet.language,
      ].join(" "),
    );
    return needle.split(/\s+/).every((word) => haystack.includes(word));
  });
}
